# Docs Modules MATH link https://docs.python.org/3/library/math.html
import math

# Operasi akar dan pangkat
print("Akar kuadrat 12 =", math.sqrt(12))
print("akar kubik 8 =", math.pow(8, 1/3))
print("2 pangkat 5 =", math.pow(2, 5))

# Pembulatan
print("ceiling 2.2 =", math.ceil(2.2)) # Pembulatan atas
print("floor 3.5 =", math.floor(3.5)) # Pembulatan bawah

# Logaritma
print("Log Natural 10 =", math.log(10))
print("Log basis 10 =", math.log10(100))